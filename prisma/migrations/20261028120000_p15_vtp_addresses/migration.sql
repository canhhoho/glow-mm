-- Map khu vực cũ → thị trấn VTP: cùng tên vùng + tên thị trấn (không phân biệt hoa thường), có bảng chính tả khác.
CREATE TEMP TABLE "_zone_map" AS
WITH alias("name", "vtp") AS (VALUES ('kamayut', 'kamaryut'), ('chan aye thar zan', 'chanayethazan'), ('chanayethar zan', 'chanayethazan'))
SELECT z."id" AS "zoneId", t."id" AS "townshipId"
FROM "ShippingZone" z
JOIN "MmState" s ON lower(s."nameEn") = lower(trim(z."region"))
JOIN "MmDistrict" d ON d."stateId" = s."id"
JOIN "MmTownship" t ON t."districtId" = d."id"
LEFT JOIN alias a ON a."name" = lower(trim(z."township"))
WHERE lower(t."nameEn") = coalesce(a."vtp", lower(trim(z."township")));

UPDATE "Address" x SET "townshipId" = m."townshipId" FROM "_zone_map" m WHERE x."zoneId" = m."zoneId";
UPDATE "AccountAddress" x SET "townshipId" = m."townshipId" FROM "_zone_map" m WHERE x."zoneId" = m."zoneId";
DELETE FROM "AccountAddress" WHERE "townshipId" IS NULL;
UPDATE "Order" o SET "townshipId" = a."townshipId" FROM "Address" a WHERE o."addressId" = a."id" AND a."townshipId" IS NOT NULL;
DROP TABLE "_zone_map";

