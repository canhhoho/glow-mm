import { expect, test } from "@playwright/test";
import { login, openOrderSection, pickAddressAdmin } from "./helpers";

test("D4: đóng ngoại lệ COD trả toàn bộ, xem tuổi nợ và báo cáo phí", async ({ page }) => {
  test.setTimeout(120000);
  await login(page, "admin@glow.local");
  await page.goto("/admin/orders/new");
  await page.getByLabel("Tên người nhận").fill("D4 COD exception");
  await page.getByLabel("SĐT", { exact: true }).fill("0978123456");
  await pickAddressAdmin(page);
  await page.getByLabel("Địa chỉ", { exact: true }).fill("No. 12, Pyay Road");
  const variant = page.getByRole("combobox", { name: "SKU / Phân loại", exact: true });
  const variantOption = variant.locator("option", { hasText: "SV-SUN-50 — Sunscreen SPF50 PA++++ (50ml)" });
  await variant.selectOption((await variantOption.getAttribute("value"))!);
  await page.getByRole("button", { name: "Tạo đơn", exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/orders\/(?!new$)[^/]+$/);
  await expect(page.getByTestId("order-status")).toContainText("Chờ xác nhận");
  const orderUrl = page.url();
  const code = (await page.getByRole("heading", { level: 1 }).textContent())!.split(" ").pop()!;
  const total = Number((await page.getByTestId("order-total").textContent())!.replace(/[^0-9]/g, ""));
  await page.getByRole("button", { name: "Xác nhận đơn", exact: true }).click();
  await expect(page.getByTestId("order-status")).toContainText("Chuẩn bị giao");
  await page.getByLabel("Đơn vị vận chuyển", { exact: true }).fill("VTP");
  await page.getByRole("button", { name: "Đã bàn giao vận chuyển", exact: true }).click();
  await expect(page.getByTestId("order-status")).toContainText("Đang giao");
  await page.getByRole("button", { name: "Giao thành công · Đã thu tiền", exact: true }).click();
  await expect(page.getByTestId("order-status")).toContainText("Hoàn tất");
  await openOrderSection(page, "order-return");
  await page.getByLabel("Trả hàng SV-SUN-50", { exact: true }).fill("1");
  const qc = page.getByLabel("Vị trí chờ kiểm tra", { exact: true });
  if (await qc.count()) await qc.selectOption((await qc.locator("option", { hasText: "MM-QC" }).getAttribute("value"))!);
  await page.getByLabel("Lý do trả", { exact: true }).fill("Khách trả toàn bộ — kiểm thử COD");
  page.once("dialog", (d) => d.accept());
  await page.getByRole("button", { name: "Ghi nhận trả hàng", exact: true }).click();
  await expect(page.getByTestId("order-status")).toContainText("Trả hàng");
  await page.goto("/admin/orders/cod?filter=exception");
  await expect(page.getByRole("link", { name: code, exact: true })).toBeVisible();
  await expect(page.getByRole("columnheader", { name: "Số ngày chờ" })).toBeVisible();
  await page.goto(orderUrl);
  await page.getByLabel("Tiền thực nhận (MMK)", { exact: true }).fill("0");
  await page.getByLabel("Phí hãng khấu trừ (MMK)", { exact: true }).fill("0");
  await page.getByLabel("Giảm thu do hoàn hàng / hoàn tiền (MMK)", { exact: true }).fill(String(total));
  await page.getByLabel("Mã giao dịch / bảng đối soát", { exact: true }).fill(`D4-${Date.now()}`);
  await page.getByLabel("Lý do và ghi chú đối soát", { exact: true }).fill("Đã đối chiếu tiền hoàn và hãng");
  page.once("dialog", (d) => d.accept());
  await page.getByRole("button", { name: "Đóng ngoại lệ COD", exact: true }).click();
  await expect(page.getByRole("button", { name: "Đóng ngoại lệ COD", exact: true })).toHaveCount(0);
  await expect(page.getByText("Đã đối chiếu tiền hoàn và hãng", { exact: false }).filter({ visible: true })).toBeVisible();
  await page.goto("/admin/orders/cod?filter=exception");
  await expect(page.getByRole("link", { name: code, exact: true })).toHaveCount(0);
  await page.goto("/admin/reports");
  await expect(page.getByTestId("r-cod-fees")).toBeVisible();
  await expect(page.getByTestId("r-recorded-profit")).toBeVisible();
});
